#include "custom_settings.h"
#include <cassert>
using namespace cube_dongle::studio;
int main() {
    CustomSettings settings, restored;
    Bytes stored;
    std::vector<Bytes> notifications;
    auto save = [&](const Bytes& bytes) {
        stored = bytes;
        return true;
    };
    auto notify = [&](const Bytes& bytes) { notifications.push_back(bytes); };
    auto call = [&](unsigned tag, const Bytes& args, bool unlocked = true) {
        Bytes request;
        Message(request, tag, args);
        return settings.Handle(request, unlocked, 3, save, notify);
    };
    Bytes reference, args, value;
    Text(reference, 2, "hold_tap.term_ms");
    Message(args, 1, reference);
    Number(value, 2, 350);
    Message(args, 2, value);
    Number(args, 3, 1);
    assert(Reader(call(3, args, false)).Get(1));
    assert(settings.Term() == 200);
    assert(Reader(call(3, args)).Get(2));
    assert(settings.Term() == 350 && restored.Load(stored) && restored.Term() == 350);
    assert(!restored.Load(Bytes(8)));
    reference.clear();
    args.clear();
    value.clear();
    Text(reference, 2, "cube.user.label");
    Message(args, 1, reference);
    Text(value, 4, "Velvet");
    Message(args, 2, value);
    Number(args, 3, 1);
    assert(Reader(call(11, args)).Get(2));
    args.clear();
    Message(args, 1, reference);
    assert(Reader(call(2, args)).Get(3));
    args.clear();
    Message(args, 1, reference);
    Number(args, 2, 3);
    Number(args, 3, 0);
    Message(args, 4, Bytes{'C', 'u'});
    Number(args, 5, 0);
    Number(args, 6, 1);
    assert(Reader(call(10, args)).Get(2));
    args.clear();
    Message(args, 1, reference);
    Number(args, 2, 3);
    Number(args, 3, 2);
    Message(args, 4, Bytes{'b'});
    Number(args, 5, 1);
    Number(args, 6, 1);
    assert(Reader(call(10, args)).Get(2));
    assert(restored.Load(stored));
    reference.clear();
    args.clear();
    value.clear();
    Text(reference, 2, "cube.user.array");
    Message(args, 1, reference);
    Bytes scalar, array;
    Number(scalar, 2, 7);
    Number(array, 1, 0);
    Number(array, 2, 1);
    Message(array, 3, scalar);
    Message(value, 5, array);
    Message(args, 2, value);
    Number(args, 3, 1);
    assert(Reader(call(11, args)).Get(2));
    args.clear();
    Message(args, 1, reference);
    Message(args, 2, scalar);
    Number(args, 3, 1);
    assert(Reader(call(7, args)).Get(2));
    args.clear();
    Message(args, 1, reference);
    Number(args, 2, 1);
    assert(Reader(call(8, args)).Get(2));
    assert(!notifications.empty());
    assert(restored.Load(stored));
}
